#!/usr/bin/env node
// Builds LevelGuide\QuestXP.lua from forever-db (GPL-3.0, the Polestar project's World of Warcraft: Forever
// quest database): each quest's full XP reward and the kills its objectives take, for LevelGuide's XP
// projection (Planner.lua). No network; it only reads the JSONL tables as data.
//
//     node tools\gen_questxp.js <path\to\forever-db> [LevelGuide\QuestXP.lua]
//
// Only quests already in LevelGuide\QuestDB.lua are written (the same Alliance/neutral set).
// Record: q[id] = "xp" or "xp|mob:kills[:e];mob:kills" where mob is the mid level of the mob to kill (kill
// objectives) or of the likeliest dropper (item objectives: kills = ceil(count / drop chance)), e = elite.
// Objectives picked up from objects, given by vendors or with no known drop chance add no kills.
'use strict';
const fs = require('fs');
const path = require('path');

const SRC = process.argv[2];
const ROOT = path.join(__dirname, '..');
const OUT = process.argv[3] || path.join(ROOT, 'LevelGuide', 'QuestXP.lua');
if (!SRC || !fs.existsSync(path.join(SRC, 'data', 'quest.jsonl'))) {
    console.error('usage: node tools/gen_questxp.js <forever-db folder> [out.lua]');
    process.exit(2);
}
function read(name) {
    const rows = [];
    for (const line of fs.readFileSync(path.join(SRC, 'data', name + '.jsonl'), 'utf8').split('\n')) {
        if (line.trim()) rows.push(JSON.parse(line));
    }
    return rows;
}
function group(rows, key) {
    const map = new Map();
    for (const row of rows) {
        const k = key(row);
        if (!map.has(k)) map.set(k, []);
        map.get(k).push(row);
    }
    return map;
}
const index = JSON.parse(fs.readFileSync(path.join(SRC, 'index.json'), 'utf8'));
const dbText = fs.readFileSync(path.join(ROOT, 'LevelGuide', 'QuestDB.lua'), 'utf8');
const qStart = dbText.indexOf('q = {');
const wanted = new Set();
for (const m of dbText.slice(qStart).matchAll(/^\[(\d+)\]="/gm)) wanted.add(Number(m[1]));

const quests = read('quest');
const objectives = group(read('quest_objective'), r => r.quest);
const npcs = new Map(read('npc').map(r => [r.id, r]));
const sources = group(read('item_source'), r => r.item);

function mob(id) {
    const n = npcs.get(id);
    if (!n || !n.level_min) return null;
    return { level: Math.floor((n.level_min + (n.level_max || n.level_min)) / 2), elite: (n.rank || 0) >= 1 };
}
const lines = [];
let count = 0;
for (const q of quests.sort((a, b) => a.id - b.id)) {
    if (!wanted.has(q.id)) continue;
    const kills = [];
    for (const o of (objectives.get(q.id) || []).sort((a, b) => (a.n || 0) - (b.n || 0))) {
        if (o.kind === 'kill') {
            const m = mob(o.target);
            if (m) kills.push(`${m.level}:${o.count || 1}${m.elite ? ':e' : ''}`);
        } else if (o.kind === 'item') {
            const list = sources.get(o.target) || [];
            if (list.some(s => s.kind === 'object')) continue;   // gathered: no kills
            let best = null;
            for (const s of list) {
                if (s.kind === 'npc' && s.chance > 0 && (!best || s.chance > best.chance)) best = s;
            }
            const m = best && mob(best.id);
            if (m) kills.push(`${m.level}:${Math.ceil((o.count || 1) / (Math.min(best.chance, 100) / 100))}${m.elite ? ':e' : ''}`);
        }
    }
    const xp = q.xp || 0;
    if (!xp && !kills.length) continue;
    lines.push(`[${q.id}]="${xp}${kills.length ? '|' + kills.join(';') : ''}",`);
    count++;
}
const out = `-- LevelGuide quest XP: GENERATED by tools\\gen_questxp.js; do not edit by hand.
-- Built from forever-db ${index.version || ''} (the Polestar project's World of Warcraft: Forever quest database,
-- https://github.com/fitzforge/polestar), GPL-3.0; derived work under the GNU GPL version 3 (see LICENSE,
-- NOTICE.md for forever-db's own credits). World of Warcraft names and game data (c) Blizzard Entertainment.
-- q[id] = "xp" or "xp|mob:kills[:e];...": full reward, then the mob level and kills each objective takes.
LevelGuideQuestXP = { q = {
${lines.join('\n')}
} }
`;
fs.writeFileSync(OUT, out);
console.log(`${count} quests -> ${OUT}`);
