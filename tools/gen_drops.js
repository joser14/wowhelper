// Generates QuestMobs\Drops.lua: drop chances of quest-objective items, per NPC.
//
//   node tools\gen_drops.js <path\to\FastLoot\Data\DropData.lua>
//
// Source: FastLoot's Data\DropData.lua (https://github.com/ca33u/fastloot, GPL-3.0, by ca33u), which its
// tools/build_drops.py generates from the cMaNGOS classic database (https://github.com/cmangos/classic-db,
// GPL-3.0): one effective chance per item per creature, references and loot groups resolved. The file is read
// as text (never loaded or run). Kept: only items that are "i<itemID>" objectives of a quest in our
// LevelGuide\QuestDB.lua, so the table stays small. Item names come from QuestDB's i[...] section.
// Classic NPCs only: mobs new in Forever are not in classic-db, so they get no line (never a guess).
// Output is GPL-3.0 (derived from GPL-3.0 data); credits are in NOTICE.md.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = process.argv[2];
if (!src) {
    console.error('usage: node tools\\gen_drops.js <path to FastLoot Data\\DropData.lua>');
    process.exit(1);
}

// 1. Quest objective items and their names, from QuestDB.lua (text only).
const questDB = fs.readFileSync(path.join(root, 'LevelGuide', 'QuestDB.lua'), 'utf8').split(/\r?\n/);
const wanted = new Set();
const names = {};
let section = null;
const rowRe = /^\[(\d+)\]="((?:[^"\\]|\\.)*)",?\s*$/;
for (const line of questDB) {
    const head = line.match(/^(\w+) = \{\s*$/);
    if (head) { section = head[1]; continue; }
    if (line.startsWith('}')) { section = null; continue; }
    const m = line.match(rowRe);
    if (!m) continue;
    if (section === 'q') {
        const fields = m[2].split('|');
        const objectives = fields[8] || '';
        for (const part of objectives.split('/')) {
            const item = part.match(/^i(\d+)/);
            if (item) wanted.add(Number(item[1]));
        }
    } else if (section === 'i') {
        names[Number(m[1])] = m[2];
    }
}

// 2. FastLoot's table: [npcID]="itemID:chance[q];...".
const drops = fs.readFileSync(src, 'utf8').split(/\r?\n/);
// Items dropping from more than MAX_NPCS creatures are general loot (cloth, potions, food, gems) that a few
// quests also ask for; a per-mob chance for those says nothing useful, so they are left out.
const MAX_NPCS = 150;
const spread = {};
for (const line of drops) {
    const m = line.match(/^\[(\d+)\]="([0-9.:;q]*)"/);
    if (!m) continue;
    for (const part of m[2].split(';')) {
        const id = Number(part.split(':')[0]);
        spread[id] = (spread[id] || 0) + 1;
    }
}
const out = [];
const usedItems = new Set();
let rows = 0;
for (const line of drops) {
    const m = line.match(/^\[(\d+)\]="([0-9.:;q]*)",?\s*$/);
    if (!m) continue;
    rows++;
    const kept = [];
    for (const part of m[2].split(';')) {
        const p = part.match(/^(\d+):([0-9.]+)q?$/);
        if (!p) continue;
        const item = Number(p[1]);
        const chance = Number(p[2]);
        if (wanted.has(item) && names[item] && spread[item] <= MAX_NPCS && chance > 0 && chance <= 100) {
            kept.push(`${item}:${p[2]}`);
            usedItems.add(item);
        }
    }
    if (kept.length) out.push(`[${m[1]}]="${kept.join(';')}",`);
}
if (rows < 1000) {
    console.error(`only ${rows} rows read from ${src}; is it FastLoot's DropData.lua?`);
    process.exit(1);
}

const nameLines = [...usedItems].sort((a, b) => a - b).map((id) => `[${id}]="${names[id]}",`);
const header = [
    '-- QuestMobs drop chances: GENERATED by tools\\gen_drops.js; do not edit by hand.',
    '-- Regenerate: node tools\\gen_drops.js <path\\to\\FastLoot\\Data\\DropData.lua>',
    '--',
    '-- Drop chances from the cMaNGOS classic database (https://github.com/cmangos/classic-db, GPL-3.0), as',
    '-- resolved into one chance per item per creature by FastLoot (https://github.com/ca33u/fastloot, GPL-3.0,',
    '-- by ca33u). Kept: items that are objectives of quests in LevelGuide\\QuestDB.lua (names from there; see',
    '-- its header for its sources). This file is a derived work under the GNU General Public License version 3',
    '-- (see LICENSE). Classic NPCs only: mobs new in World of Warcraft: Forever are absent and get no line.',
    '-- World of Warcraft names and game data (c) Blizzard Entertainment.',
    '--',
    '--   npc[npcID] = "itemID:chance;..."  chance in percent (classic values; Forever may differ)',
    '--   names[itemID] = item name',
    'QuestMobsDrops = {',
    'names = {',
];
const text = header.concat(nameLines, ['},', 'npc = {'], out, ['},', '}', '']).join('\n');
fs.writeFileSync(path.join(root, 'QuestMobs', 'Drops.lua'), text, 'utf8');
console.log(`objective items ${wanted.size}, NPC rows read ${rows}, NPCs kept ${out.length}, items kept ${usedItems.size}`);
